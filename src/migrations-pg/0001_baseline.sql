-- Triggers
-- agent_messages_delivered_needs_ts: the SQLite trigger repairs a row that was closed as delivered without a timestamp.
-- A BEFORE trigger gives the same net row without the self-UPDATE.
CREATE FUNCTION marveen_agent_messages_delivered_needs_ts() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status = 'delivered' AND NEW.delivered_at IS NULL THEN
    NEW.delivered_at := extract(epoch from now())::bigint;
    NEW.result := COALESCE(NEW.result, 'closed-without-delivery');
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER agent_messages_delivered_needs_ts BEFORE UPDATE OF status ON agent_messages
  FOR EACH ROW EXECUTE FUNCTION marveen_agent_messages_delivered_needs_ts();

CREATE FUNCTION marveen_artifacts_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := extract(epoch from now())::bigint;
  RETURN NEW;
END
$$;
CREATE TRIGGER artifacts_updated_at BEFORE UPDATE ON artifacts
  FOR EACH ROW EXECUTE FUNCTION marveen_artifacts_updated_at();

CREATE FUNCTION marveen_kanban_cards_status_bumps_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status <> OLD.status AND NEW.updated_at = OLD.updated_at THEN
    NEW.updated_at := extract(epoch from now())::bigint;
  END IF;
  RETURN NEW;
