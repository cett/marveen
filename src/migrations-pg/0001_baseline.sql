-- PostgreSQL baseline of the Marveen schema, cut from the SQLite end state at schema_version 95.
-- Generated from the SQLite migration chain (an empty database after applyMigrations): 85 tables, 740 columns,
-- 116 indexes in the SQLite end state (117 here: one more for the lower-case username, see below; 10 partial), 14 UNIQUE constraints,
-- 17 foreign keys, 65 CHECK constraints.
--
-- Type map: TEXT -> text; INTEGER -> bigint; REAL -> double precision; BLOB -> bytea; the 18 0/1 flag columns -> smallint + CHECK (col IN (0, 1)),
-- not boolean, because the code compares them with = 1. unixepoch() -> (extract(epoch from now())::bigint).
-- AUTOINCREMENT (and the two rowid-alias keys) -> bigint GENERATED BY DEFAULT AS IDENTITY.
-- kanban_cards has no rowid in PostgreSQL: its running number (#N) is the explicit identity column seq.
-- dashboard_users.username is UNIQUE COLLATE NOCASE in SQLite: a unique index on lower(username) here.
--
-- Left out on purpose (later phases): the FTS5 tables memories_fts, artifacts_fts, workspace_docs_fts and their nine sync triggers;
-- the vec_* tables (created outside the migrations, src/db/vector.ts); the two kanban_cards_due_date_integer_* triggers
-- (SQLite dynamic typing: due_date is a bigint here, the application passes an epoch); the two memories_content_not_blank_* triggers
-- are one CHECK on memories.content (same character set as isBlankContent); the SQLite schema_version rows are not copied.
-- RLS roles and policies are not part of this file.
--
-- Added at the end: the unixepoch() function (the module SQL calls it) and the seed rows the SQLite chain inserts
-- (6 tables), generated by scripts/generate-pg-baseline-seed.ts between the BEGIN/END GENERATED SEED markers.

